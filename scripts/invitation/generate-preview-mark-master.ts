/**
 * Regenerates `src/lib/invitation/preview/preview-mark-master.generated.ts`: the rotated
 * single-mark PNG the Cloudflare Images binding scales and repeats (it cannot rasterize SVG).
 * Run after changing `preview-mark-svg.ts`; a unit test fails while the two disagree.
 *
 * Usage: pnpm invitation:preview-mark:generate
 */
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';
import {
	buildPreviewMarkInstanceSvg,
	previewMarkInstanceSize,
} from '../../src/lib/invitation/preview/preview-mark-instances.ts';
import { PREVIEW_MARK_MASTER_PX_PER_UNIT } from '../../src/lib/invitation/preview/preview-mark-master-config.ts';

const OUTPUT = 'src/lib/invitation/preview/preview-mark-master.generated.ts';

const png = await sharp(Buffer.from(buildPreviewMarkInstanceSvg(PREVIEW_MARK_MASTER_PX_PER_UNIT)))
	.png({ compressionLevel: 9, effort: 10 })
	.toBuffer();
const blank = await sharp({
	create: { width: 1, height: 1, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
})
	.png()
	.toBuffer();
const size = previewMarkInstanceSize(PREVIEW_MARK_MASTER_PX_PER_UNIT);

writeFileSync(
	OUTPUT,
	`/**
 * Generated by scripts/invitation/generate-preview-mark-master.ts; do not edit by hand.
 * One rotated preview mark at ${PREVIEW_MARK_MASTER_PX_PER_UNIT} px per cap unit (${size.width}x${size.height}).
 */
export const PREVIEW_MARK_MASTER_PNG_BASE64 =
	'${png.toString('base64')}';

/** Transparent 1x1 PNG, stretched to the image size as the canvas for mark overlays. */
export const TRANSPARENT_PIXEL_PNG_BASE64 = '${blank.toString('base64')}';
`,
);
console.log(`Wrote ${OUTPUT} (${png.length} bytes of PNG).`);
