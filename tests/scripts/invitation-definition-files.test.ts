import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
	clientInvitationAssetDir,
	invitationDefinitionFile,
	isInvitationDefinitionPath,
	listClientInvitationSlugs,
	listInvitationDefinitionFiles,
} from '../../scripts/shared/invitation-definition-files.ts';
import {
	CLIENT_REGISTRY_FILE,
	renderClientRegistry,
} from '../../scripts/provision/invitations/generate-client-registry.ts';
import { CLIENT_INVITATION_DEFINITIONS } from '../../scripts/provision/invitations/client-registry.generated.ts';
import { listInvitationDefinitions } from '../../scripts/provision/invitations/registry.ts';

/** Single-file definitions that predate the folder format. This list may only shrink. */
const FROZEN_LEGACY_SLUGS = [
	'abril-michelle-becerra-rea',
	'aithan-darell',
	'alba-rosa-quinonez',
	'allison-scarlett',
	'america',
	'daniela-y-martin',
	'destenid-sofia',
	'leslie-perez',
	'melissa-y-luis-osmar',
	'mia-pintor',
	'naydelin-paredes',
	'norma-hernandez',
	'olivia-y-antonio',
	'renata',
	'romina-rios-chaparro',
	'valentina-hernandez',
	'victoria-y-roberto',
];

function fixtureRoot(): string {
	const root = fs.mkdtempSync(path.join(os.tmpdir(), 'invitation-definition-files-'));
	const write = (file: string) => {
		fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
		fs.writeFileSync(path.join(root, file), '');
	};
	write('scripts/provision/invitations/legacy-one.ts');
	write('src/invitations/clients/zeta-y-omar/invitation.ts');
	write('src/invitations/clients/ana-lucia/invitation.ts');
	write('src/invitations/clients/ana-lucia/profile.scss');
	write('src/invitations/clients/draft-without-definition/profile.scss');
	return root;
}

describe('invitation definition files', () => {
	const root = fixtureRoot();
	afterAll(() => fs.rmSync(root, { recursive: true, force: true }));

	it('lists client folders that hold an invitation.ts, sorted', () => {
		expect(listClientInvitationSlugs(root)).toEqual(['ana-lucia', 'zeta-y-omar']);
		expect(listInvitationDefinitionFiles(root)).toEqual([
			'scripts/provision/invitations/legacy-one.ts',
			'src/invitations/clients/ana-lucia/invitation.ts',
			'src/invitations/clients/zeta-y-omar/invitation.ts',
		]);
	});

	it('resolves a definition file to its folder, else to the legacy module', () => {
		expect(invitationDefinitionFile('ana-lucia', root)).toBe(
			'src/invitations/clients/ana-lucia/invitation.ts',
		);
		expect(invitationDefinitionFile('legacy-one', root)).toBe(
			'scripts/provision/invitations/legacy-one.ts',
		);
		expect(clientInvitationAssetDir('ana-lucia')).toBe(
			'src/invitations/clients/ana-lucia/assets',
		);
	});

	it('recognizes only definition paths', () => {
		expect(isInvitationDefinitionPath('scripts/provision/invitations/renata.ts')).toBe(true);
		expect(isInvitationDefinitionPath('src\\invitations\\clients\\ana\\invitation.ts')).toBe(
			true,
		);
		expect(isInvitationDefinitionPath('src/invitations/clients/ana/profile.scss')).toBe(false);
		expect(isInvitationDefinitionPath('src/invitations/clients/ana/assets/a.ts')).toBe(false);
		expect(isInvitationDefinitionPath('scripts/provision/invitations/sub/x.ts')).toBe(false);
	});

	it('renders the generated registry from the folder slugs', () => {
		expect(renderClientRegistry(['ana-lucia', 'zeta-y-omar'])).toBe(
			[
				'// Generated by `pnpm invitation:registry` from src/invitations/clients/*/invitation.ts.',
				'// Do not edit by hand.',
				"import type { InvitationDefinition } from './invitation-definition.ts';",
				"import invitation0 from '../../../src/invitations/clients/ana-lucia/invitation.ts';",
				"import invitation1 from '../../../src/invitations/clients/zeta-y-omar/invitation.ts';",
				'',
				'export const CLIENT_INVITATION_DEFINITIONS: readonly InvitationDefinition[] = [',
				'\tinvitation0,',
				'\tinvitation1,',
				'];',
				'',
			].join('\n'),
		);
	});

	it('keeps the committed generated registry equal to the folders on disk', () => {
		const committed = fs.readFileSync(CLIENT_REGISTRY_FILE, 'utf8').replaceAll('\r\n', '\n');
		expect(committed).toBe(renderClientRegistry(listClientInvitationSlugs()));
	});
});

describe('invitation registry', () => {
	const clientSlugs = new Set(CLIENT_INVITATION_DEFINITIONS.map((definition) => definition.slug));

	it('accepts no new single-file definitions', () => {
		const legacy = listInvitationDefinitions()
			.map((definition) => definition.slug)
			.filter((slug) => !clientSlugs.has(slug));
		for (const slug of legacy)
			expect([slug, FROZEN_LEGACY_SLUGS.includes(slug)]).toEqual([slug, true]);
	});

	it('keeps each client definition inside its own folder', () => {
		for (const definition of CLIENT_INVITATION_DEFINITIONS) {
			const folder = path.join('src/invitations/clients', definition.slug);
			expect(fs.existsSync(path.join(folder, 'invitation.ts'))).toBe(true);
			expect(definition.assetDir).toBe(clientInvitationAssetDir(definition.slug));
			if (fs.existsSync(path.join(folder, 'profile.scss')))
				expect(definition.visualProfileId).toBe(definition.slug);
		}
	});
});
